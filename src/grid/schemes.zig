/// Look up a scheme by key. Returns null if no match.
pub fn lookup(key: []const u8) ?*const Scheme {
    for (&all) |*s| {
        if (std.mem.eql(u8, s.key, key)) return s;
    }
    return null;
}

test "scheme: lookup finds known keys, returns null for missing" {
    try std.testing.expect(lookup("solarized_dark") != null);
    try std.testing.expect(lookup("nord") != null);
    try std.testing.expect(lookup("does-not-exist") == null);
    try std.testing.expect(lookup("") == null);
}
