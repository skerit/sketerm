//! Build-time generator of the tools/list JSON that `ipc/mcp_tools.zig`
//! serves, rendered from its `TOOLS` table by `mcp_tools.writeToolJson`.
//!
//! It runs at build time because the same rendering as comptime code
//! (per-byte escaping into comptime arrays) cost the analysis of every
//! MCP-bearing root more than ten minutes. Its output is a Zig module
//! (`mcp_tools_json`) holding the whole array as one newline-free
//! multiline literal plus each tool's span in it; `mcp_tools.zig` checks
//! the span count against the table it was generated from.
//!
//! Invoked by `build.zig` as `mcp_tools_gen <out .zig file>`.

const std = @import("std");
const mcp_tools = @import("ipc/mcp_tools.zig");

pub fn main(init: std.process.Init) !u8 {
    const gpa = init.gpa;
    const io = init.io;
    var args = std.process.Args.Iterator.init(init.minimal.args);
    _ = args.skip();
    const out_path = args.next() orelse return usage();
    if (args.next() != null) return usage();

    var json: std.Io.Writer.Allocating = .init(gpa);
    defer json.deinit();
    var spans: [mcp_tools.TOOLS.len][2]usize = undefined;
    try json.writer.writeByte('[');
    for (mcp_tools.TOOLS, &spans, 0..) |t, *span, i| {
        if (i > 0) try json.writer.writeByte(',');
        span[0] = json.written().len;
        mcp_tools.writeToolJson(&json.writer, t) catch |err| {
            std.debug.print("mcp_tools_gen: tool '{s}': {t}\n", .{ t.name, err });
            return 1;
        };
        span[1] = json.written().len;
    }
    try json.writer.writeByte(']');
    // The literal below is one source line: any control byte (a newline
    // above all) would end or corrupt it, and MCP stdio framing forbids
    // a newline in the advertised list anyway.
    for (json.written()) |ch| {
        if (ch < 0x20) {
            std.debug.print("mcp_tools_gen: control byte 0x{x:0>2} in the tool list\n", .{ch});
            return 1;
        }
    }

    var out: std.Io.Writer.Allocating = .init(gpa);
    defer out.deinit();
    const w = &out.writer;
    try w.writeAll("//! Generated by src/mcp_tools_gen.zig from mcp_tools.TOOLS; never edit.\n\n");
    try w.writeAll("pub const TOOLS_JSON: []const u8 =\n    \\\\");
    try w.writeAll(json.written());
    try w.writeAll("\n;\n\npub const TOOL_SPANS = [_][2]usize{\n");
    for (spans) |span| try w.print("    .{{ {d}, {d} }},\n", .{ span[0], span[1] });
    try w.writeAll("};\n");
    try std.Io.Dir.cwd().writeFile(io, .{ .sub_path = out_path, .data = out.written() });
    return 0;
}

fn usage() u8 {
    std.debug.print("usage: mcp_tools_gen <out .zig file>\n", .{});
    return 2;
}
